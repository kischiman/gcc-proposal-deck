// Generates public/budget-embed.css from public/budget.css.
//
// The deck renders budget lines on two of its slides, so it needs the budget's
// component styles — but the two stylesheets disagree about nine class names
// (.line, .phase, .note, .row, .btn, .tag, .ghost, .eyebrow, .plines), and the deck
// would lose every one of those arguments. So the board styles are re-emitted here
// under .budget-scope, while the dialogs — which mount on <body>, outside any scope,
// and collide with nothing — are emitted as they are.
//
// budget.css stays the single source of truth. Re-run this after editing it:
//
//   node build-budget-embed.mjs   →   public/budget-embed.css

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, "public", "budget.css");
const OUT = path.join(HERE, "public", "budget-embed.css");

// Page furniture and the admin panel: the deck has its own, or never shows them.
const SKIP = [
  /^\*$/, /^\[hidden\]$/, /^body$/, /^html$/, /^h1$/, /^h3$/, /^:root$/,
  /^\.wrap/, /^\.top/, /^\.footnote/, /^\.rates/, /^\.rate\b/, /^\.rate-grid/, /^\.hint/,
  /^\.gate/, /^\.admin-only/, /^\.storage-warn/, /^\.prefill/, /^\.switch/,
  /^\.people-block/, /^\.person/, /^\.pname/, /^\.pnums/, /^\.diag/, /^\.remove/,
  /^\.plines/, /^\.claimed-by/, /^\.claim-note/, /^\.empty-note/, /^\.phase-foot/,
  /\.admin\b/, /\.danger\b/, /^\.modal-body/,
];

// Dialog surfaces live on <body>, outside .budget-scope, and clash with nothing.
const UNSCOPED = /(^|\s|\.)(scrim|modal|modal-task|modal-actions|x|calc|calc-total|others|others-label|others-note|other|identity|linkish|proposal|proposals|on-tag|pnote|scope-label)\b/;

// `.line:not(.admin)` is a rule *for* the board, phrased by excluding the admin panel.
// Testing the raw selector would see ".admin" and drop it — losing the very rule the
// board needs. Strip :not(...) before deciding.
const skip = (sel) => {
  const bare = sel.replace(/:not\([^)]*\)/g, "").trim();
  return SKIP.some((re) => re.test(bare));
};

function rewrite(selectorList) {
  const kept = selectorList
    .split(",")
    .map((s) => s.trim())
    .filter((s) => s && !skip(s))
    .map((s) => (UNSCOPED.test(s) ? s : `.budget-scope ${s}`));
  return kept.length ? kept.join(",\n") : null;
}

// Split a stylesheet body into top-level blocks, respecting nesting.
function blocks(css) {
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === "{") {
      depth++;
    } else if (c === "}") {
      depth--;
      if (depth === 0) {
        out.push(css.slice(start, i + 1));
        start = i + 1;
      }
    }
  }
  return out.map((b) => b.trim()).filter(Boolean);
}

function convert(css) {
  const parts = [];
  for (const block of blocks(css)) {
    const open = block.indexOf("{");
    const prelude = block.slice(0, open).trim();
    const body = block.slice(open + 1, block.lastIndexOf("}"));

    if (prelude.startsWith("@keyframes")) {
      parts.push(block); // steps are not selectors — pass through untouched
      continue;
    }
    if (prelude.startsWith("@media") || prelude.startsWith("@supports")) {
      const inner = convert(body);
      if (inner.trim()) parts.push(`${prelude} {\n${inner.replace(/^/gm, "  ")}\n}`);
      continue;
    }
    if (prelude.startsWith("@")) continue;

    const sel = rewrite(prelude);
    if (sel) parts.push(`${sel} {${body}}`);
  }
  return parts.join("\n\n");
}

const src = fs.readFileSync(SRC, "utf8");
const comments = src.match(/^\/\*[\s\S]*?\*\//);
const stripped = src.replace(/\/\*[\s\S]*?\*\//g, "");

const header = `/* GENERATED by build-budget-embed.mjs from budget.css — do not edit by hand.
 *
 * Board styles are scoped to .budget-scope so they cannot fight the deck's own
 * .line / .phase / .note / .row. Dialog styles are unscoped: they mount on <body>.
 */

/* The two stylesheets share a palette; these are the only tokens deck.css lacks. */
:root {
  --claimed: #3f6b4a;
  --claimed-soft: #edf3ee;
}
`;

fs.writeFileSync(OUT, header + "\n" + convert(stripped) + "\n");
const n = fs.readFileSync(OUT, "utf8").split("\n").length;
console.log(`wrote ${path.relative(HERE, OUT)} — ${n} lines`);
