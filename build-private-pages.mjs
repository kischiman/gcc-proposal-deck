// Turns the gated pages into a module the app imports.
//
// Why this exists, rather than reading the files at runtime:
//
//   1. Anything inside public/ is served by the host's CDN before a request ever
//      reaches the application. /admin and /team write to the shared board, so if they
//      sit there they are open to anyone with the link and no server-side gate can
//      stop it. They live in private/ instead.
//
//   2. A serverless bundle ships what the bundler can *trace* — imports. A loose file
//      read with fs is not traced, so private/admin.html could simply be absent at
//      runtime. Emitting the pages as a module makes them an ordinary import.
//
// The HTML stays HTML: edit private/*.html and re-run this.
//
//   node build-private-pages.mjs   →   private/pages.js

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(HERE, "private");
const OUT = path.join(DIR, "pages.js");

const files = fs.readdirSync(DIR).filter((f) => f.endsWith(".html")).sort();

if (!files.length) {
  console.error("build-private-pages: no .html files in private/ — nothing to emit");
  process.exit(1);
}

// JSON.stringify does the escaping, so no quote, backslash or backtick in the markup
// can break out of the literal. That class of bug has bitten this project once already.
const entries = files
  .map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(DIR, f), "utf8"))},`)
  .join("\n");

const module_ = `// GENERATED by build-private-pages.mjs — do not edit by hand.
//
// The gated pages, as strings. Edit private/*.html and re-run the generator.

export const PAGES = {
${entries}
};
`;

fs.writeFileSync(OUT, module_);
console.log(`wrote ${path.relative(HERE, OUT)} — ${files.length} page(s): ${files.join(", ")}`);
